"""Coverage report: included, missing, duplicate, unverified and unusable sources.

    python -m phq_ingest.coverage --db build/package/content.sqlite \
        --registry content/source_registry.json --out-json build/coverage_report.json \
        --out-md docs/COVERAGE_REPORT.md
"""
from __future__ import annotations

import argparse
import json
import sqlite3
from collections import Counter, defaultdict
from pathlib import Path

from .util import read_json, write_json


def report(db: Path, registry: Path) -> dict:
    reg = read_json(registry)
    con = sqlite3.connect(db)
    con.row_factory = sqlite3.Row
    rows = [dict(r) for r in con.execute(
        "SELECT source_id, title, citation, jurisdiction_label, level, municipality, doc_type, publisher_status, "
        "extraction_quality, trusted_for_guidance, verification_status, consolidation, pages, quality_notes FROM sources")]
    prov_counts = dict(con.execute("SELECT source_id, count(*) FROM provisions GROUP BY source_id").fetchall())
    gaps = [dict(r) for r in con.execute("SELECT gap_id, category, title FROM coverage_gaps")]
    by_label = defaultdict(list)
    for r in rows:
        r["provisions"] = prov_counts.get(r["source_id"], 0)
        by_label[r["jurisdiction_label"]].append(r)
    out = {
        "totals": {
            "sources": len(rows),
            "duplicate_uploads": len(reg.get("duplicates", [])),
            "trusted_for_guidance": sum(r["trusted_for_guidance"] for r in rows),
            "verified_against_publisher": sum(1 for r in rows if r["verification_status"] not in ("Not verified", None)),
            "by_quality": dict(Counter(r["extraction_quality"] for r in rows)),
            "by_jurisdiction": {k: len(v) for k, v in sorted(by_label.items())},
        },
        "unusable": [r["source_id"] for r in rows if r["extraction_quality"] == "unusable"],
        "image_only": [r["source_id"] for r in rows if r["extraction_quality"] == "image-only"],
        "reference_conversions": [r["source_id"] for r in rows if r["publisher_status"].startswith("reference conversion")],
        "duplicates": reg.get("duplicates", []),
        "gaps": gaps,
        "sources": rows,
    }
    con.close()
    return out


def markdown(rep: dict) -> str:
    t = rep["totals"]
    lines = [
        "# Coverage report",
        "",
        "Generated by `tools/phq_ingest/coverage.py` from the built content database. Contains metadata only.",
        "",
        "## Totals",
        "",
        f"- Distinct sources: **{t['sources']}**",
        f"- Duplicate uploads (identical SHA-256, not ingested twice): **{t['duplicate_uploads']}**",
        f"- Sources eligible for guided analysis (publisher-issued, automated checks passed): **{t['trusted_for_guidance']}**",
        f"- Sources verified against the official publisher: **{t['verified_against_publisher']}** (verification has not been performed)",
        "",
        "| Extraction quality | Sources |",
        "|---|---|",
    ]
    for k, v in sorted(t["by_quality"].items()):
        lines.append(f"| {k} | {v} |")
    lines += ["", "| Jurisdiction | Sources |", "|---|---|"]
    for k, v in t["by_jurisdiction"].items():
        lines.append(f"| {k} | {v} |")
    lines += ["", "## Unusable sources", ""]
    lines += [f"- {s}" for s in rep["unusable"]] or ["- None"]
    lines += ["", "## Image-only sources (view the original; OCR text unverified)", ""]
    lines += [f"- {s}" for s in rep["image_only"]] or ["- None"]
    lines += ["", "## Reference conversions (not publisher-issued)", ""]
    lines += [f"- {s}" for s in rep["reference_conversions"]] or ["- None"]
    lines += ["", "## Duplicate uploads", ""]
    lines += [f"- {d['original_filename']} → duplicate of `{d['duplicate_of']}`" for d in rep["duplicates"]] or ["- None"]
    lines += ["", "## Known gaps (missing material)", ""]
    lines += [f"- **{g['title']}** (`{g['gap_id']}`, {g['category']})" for g in rep["gaps"]]
    lines += ["", "## All sources", "", "| Source ID | Jurisdiction | Title | Quality | Guided | Provisions | Consolidation |", "|---|---|---|---|---|---|---|"]
    for r in sorted(rep["sources"], key=lambda r: (r["jurisdiction_label"], r["source_id"])):
        title = r["title"].replace("|", "/")
        lines.append(f"| `{r['source_id']}` | {r['jurisdiction_label']} | {title} | {r['extraction_quality']} | "
                     f"{'yes' if r['trusted_for_guidance'] else 'no'} | {r['provisions']} | {r['consolidation'] or 'Unknown'} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", type=Path, required=True)
    ap.add_argument("--registry", type=Path, required=True)
    ap.add_argument("--out-json", type=Path, required=True)
    ap.add_argument("--out-md", type=Path, required=True)
    a = ap.parse_args()
    rep = report(a.db, a.registry)
    write_json(a.out_json, rep)
    a.out_md.parent.mkdir(parents=True, exist_ok=True)
    a.out_md.write_text(markdown(rep), encoding="utf-8")
    print(json.dumps(rep["totals"], indent=1))


if __name__ == "__main__":
    main()
